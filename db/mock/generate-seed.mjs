#!/usr/bin/env node
/**
 * Builds db/mock/generated/02-seed.sql — mock CSSD data for local testing.
 *
 * Input: the JSON that /api/parse-xlsx returns for the hospital's
 * "สถิติ จ่าย ปีงบประมาณ 2568.xlsx" (set names, unit prices and per-month
 * quantities). Each item's monthly quantity is expanded into that many
 * SupplyTb rows (one row = one dispensed pack), spread over the month with
 * made-up departments / staff. So the DB-backed dashboard for FY2568 should
 * reproduce the Excel report's per-item, per-month numbers exactly — that's
 * what lets us check the SQL + aggregation end to end before real data exists.
 *
 * Usage:
 *   curl -s -F "file=@test/สถิติ จ่าย ปีงบประมาณ 2568.xlsx" \
 *     http://localhost:3000/api/parse-xlsx > /some/scratch/supply-2568.json
 *   node db/mock/generate-seed.mjs /some/scratch/supply-2568.json
 *
 * The output is gitignored: it's derived from real hospital data (test/ is
 * gitignored for the same reason).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const inputPath = process.argv[2];
if (!inputPath) {
  console.error("usage: node db/mock/generate-seed.mjs <parse-xlsx-output.json>");
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(inputPath, "utf8"));
if (data.reportType !== "monthly" || !Array.isArray(data.items)) {
  console.error(`expected a monthly-matrix report, got reportType=${data.reportType}`);
  process.exit(1);
}

const sqlStr = (s) => (s == null ? "NULL" : `N'${String(s).replace(/'/g, "''")}'`);

/** Plain INSERTs are capped at 1000 rows per VALUES list. */
function insertChunks(table, columns, rows) {
  const out = [];
  for (let i = 0; i < rows.length; i += 900) {
    const chunk = rows.slice(i, i + 900);
    out.push(
      `INSERT INTO ${table} (${columns.join(", ")}) VALUES\n` +
        chunk.map((r) => `  (${r.join(", ")})`).join(",\n") +
        ";"
    );
  }
  return out.join("\n");
}

// ── Lookup tables ────────────────────────────────────────────────────
// Department names as seen in the screenshot (ids 0–9).
const departments = [
  [0, "เซตฝาก"], [1, "CSSD"], [2, "ER"], [3, "LR"], [4, "IPD"],
  [5, "OPD"], [6, "LAB"], [7, "ทันตกรรม"], [8, "เวชปฏิบัติ"], [9, "ANC"],
];
// Real staff names are personal data — the mock uses placeholders. Ids 0/1
// mirror the screenshot's sentinel rows (NULL and "/").
const persons = [
  [0, null], [1, "/"],
  [2, "เจ้าหน้าที่ ก"], [3, "เจ้าหน้าที่ ข"], [4, "เจ้าหน้าที่ ค"],
  [5, "เจ้าหน้าที่ ง"], [6, "เจ้าหน้าที่ จ"],
];
const dayCounts = [[1, "7"], [2, "14"], [3, "30"], [4, "45"], [5, "60"], [6, "90"], [7, "180"]];

// ── Sets + per-month quantities from the Excel report ────────────────
const sets = [];
const monthlyQty = []; // [SetTbId, CE year, month, qty]
data.items.forEach((item, i) => {
  const id = i + 1;
  const unnamed = item.name.startsWith("(ไม่ระบุชื่อรายการ");
  sets.push([id, unnamed ? "NULL" : sqlStr(item.name), Number(item.pricePerUnit || 0).toFixed(2)]);
  for (const [key, qty] of Object.entries(item.monthlyQuantity ?? {})) {
    const m = key.match(/^(\d{4})-(\d{2})$/);
    if (!m || !qty) continue;
    monthlyQty.push([id, Number(m[1]) - 543, Number(m[2]), qty]);
  }
});

const totalRows = monthlyQty.reduce((s, r) => s + r[3], 0);

const sql = `-- GENERATED by db/mock/generate-seed.mjs from ${path.basename(inputPath)} — do not edit.
-- ${sets.length} sets, ${totalRows} dispensed packs (FY${data.fiscalYear ?? "?"}).
USE CSSD;
SET NOCOUNT ON;
GO

${insertChunks("dbo.DepartTb", ["DepartTbId", "DepartTbName"], departments.map(([id, n]) => [id, sqlStr(n)]))}
${insertChunks("dbo.PersonTb", ["PersonTbId", "PersonCall"], persons.map(([id, n]) => [id, sqlStr(n)]))}
${insertChunks("dbo.DayCountTb", ["DayCountTbId", "DayCountTbName"], dayCounts.map(([id, n]) => [id, sqlStr(n)]))}
${insertChunks("dbo.SetTb", ["SetTbId", "SetTbName", "SetTbPrice"], sets)}
GO

CREATE TABLE #MockQty (SetTbId INT, Y INT, M INT, Qty INT);
${insertChunks("#MockQty", ["SetTbId", "Y", "M", "Qty"], monthlyQty)}

-- A handful of physical packs per set (barcode 10000 + PackTbNo, like the
-- screenshot), reused round-robin by the dispense rows below.
WITH PackCount AS (
  SELECT SetTbId, CASE WHEN MAX(Qty) > 5 THEN 5 ELSE MAX(Qty) END AS N
  FROM #MockQty GROUP BY SetTbId
),
Tally AS (SELECT TOP (5) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS K FROM sys.all_objects)
INSERT INTO dbo.PackTb (PackTbNo, PackBarcode, SetTbId)
SELECT ROW_NUMBER() OVER (ORDER BY p.SetTbId, t.K) - 1,
       CAST(10000 + ROW_NUMBER() OVER (ORDER BY p.SetTbId, t.K) - 1 AS NVARCHAR(50)),
       p.SetTbId
FROM PackCount p JOIN Tally t ON t.K <= p.N;

-- Screenshot's sentinel row: SupplyNo 0 with NULLs.
INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount)
VALUES (0, NULL, 0, NULL, NULL, N'0', 0);

-- One row per dispensed pack. Mostly daytime timestamps, plus deliberate
-- month-boundary ones (exact midnight on the 1st, 23:59:59.997 on the last
-- day) so month bucketing gets exercised.
WITH Tally AS (
  SELECT TOP (${Math.max(...monthlyQty.map((r) => r[3]), 1)}) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS N
  FROM sys.all_objects a CROSS JOIN sys.all_objects b
),
Packs AS (
  SELECT SetTbId, MIN(PackTbNo) AS FirstPack, COUNT(*) AS PackCount FROM dbo.PackTb GROUP BY SetTbId
),
Expanded AS (
  SELECT q.SetTbId, q.Y, q.M, q.Qty, t.N, p.FirstPack, p.PackCount,
         DATEFROMPARTS(q.Y, q.M, 1) AS MonthStart,
         DAY(EOMONTH(DATEFROMPARTS(q.Y, q.M, 1))) AS DaysInMonth
  FROM #MockQty q
  JOIN Tally t ON t.N <= q.Qty
  JOIN Packs p ON p.SetTbId = q.SetTbId
)
INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount)
SELECT
  ROW_NUMBER() OVER (ORDER BY d.SupplyDate, e.SetTbId, e.N),
  e.FirstPack + (e.N % e.PackCount),
  -- ~70% to the set's "home" department, the rest spread over 1–9
  CASE WHEN e.N % 10 < 7 THEN 2 + (e.SetTbId % 8) ELSE 1 + ((e.N + e.SetTbId) % 9) END,
  2 + ((e.N + e.SetTbId) % 5),
  d.SupplyDate,
  N'0',
  1
FROM Expanded e
CROSS APPLY (SELECT CASE
  WHEN e.N = 1 AND e.SetTbId % 5 = 0
    THEN CAST(e.MonthStart AS DATETIME)
  WHEN e.N = e.Qty AND e.SetTbId % 7 = 0
    THEN DATEADD(MILLISECOND, -3, CAST(DATEADD(MONTH, 1, e.MonthStart) AS DATETIME))
  ELSE DATEADD(MINUTE, 480 + ((e.N * 37 + e.SetTbId * 11) % 600),
         CAST(DATEADD(DAY, (e.N * 13 + e.SetTbId) % e.DaysInMonth, e.MonthStart) AS DATETIME))
END AS SupplyDate) d;

-- Just outside FY2568 on both sides — must NOT show up in the FY2568 report.
DECLARE @next INT = (SELECT MAX(SupplyNo) FROM dbo.SupplyTb);
INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount) VALUES
  (@next + 1, 0, 2, 2, '2024-09-30T23:59:59.997', N'0', 1),
  (@next + 2, 0, 2, 2, '2025-10-01T00:00:00.000', N'0', 1);

DROP TABLE #MockQty;
GO

SELECT COUNT(*) AS SupplyRows FROM dbo.SupplyTb;
GO
`;

const outDir = path.join(here, "generated");
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, "02-seed.sql");
fs.writeFileSync(outPath, sql);
console.log(`wrote ${outPath}: ${sets.length} sets, ${monthlyQty.length} set-months, ${totalRows} supply rows`);
