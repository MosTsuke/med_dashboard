#!/usr/bin/env node
/**
 * Builds db/mock/generated/02-seed.sql — mock CSSD data for local testing,
 * shaped like the real database (see db/mock/01-schema.sql).
 *
 * Input: the JSON that /api/parse-xlsx returns for a monthly-matrix Excel
 * report (we use "สถิติ จ่าย ปีงบประมาณ 2568.xlsx" for set names, unit prices
 * and per-month quantities). Note that Excel turned out NOT to come from the
 * hospital's CSSD database — it's only a convenient source of realistic
 * names and volumes. Each item's monthly quantity becomes dispense rows:
 *   - consumables (name looks like สำลี / ก๊อซ / gauze ...): PackTbNo 0,
 *     SuplyCount up to 10 per row — like the real data
 *   - everything else: one barcoded pack per dispensed piece, with its own
 *     pack date and expiry date
 * so the DB-backed dashboard for that fiscal year reproduces the Excel's
 * per-item, per-month numbers exactly — a check of the SQL + aggregation.
 *
 * Usage:
 *   curl -s -F "file=@test/สถิติ จ่าย ปีงบประมาณ 2568.xlsx" \
 *     http://localhost:3000/api/parse-xlsx > /some/scratch/supply-2568.json
 *   node db/mock/generate-seed.mjs /some/scratch/supply-2568.json
 *
 * The output is gitignored: it's derived from real hospital data.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const inputPath = process.argv[2];
if (!inputPath) {
  console.error("usage: node db/mock/generate-seed.mjs <parse-xlsx-output.json>");
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(inputPath, "utf8"));
if (data.reportType !== "monthly" || !Array.isArray(data.items)) {
  console.error(`expected a monthly-matrix report, got reportType=${data.reportType}`);
  process.exit(1);
}

const sqlStr = (s) => (s == null ? "NULL" : `N'${String(s).replace(/'/g, "''")}'`);

/** Plain INSERTs are capped at 1000 rows per VALUES list. */
function insertChunks(table, columns, rows) {
  const out = [];
  for (let i = 0; i < rows.length; i += 900) {
    const chunk = rows.slice(i, i + 900);
    out.push(
      `INSERT INTO ${table} (${columns.join(", ")}) VALUES\n` +
        chunk.map((r) => `  (${r.join(", ")})`).join(",\n") +
        ";"
    );
  }
  return out.join("\n");
}

// ── Lookup tables ────────────────────────────────────────────────────
const departments = [
  [0, "เซตฝาก"], [1, "CSSD"], [2, "ER"], [3, "LR"], [4, "IPD"],
  [5, "OPD"], [6, "LAB"], [7, "ทันตกรรม"], [8, "เวชปฏิบัติ"], [9, "ANC"],
];
// Real staff names are personal data — the mock uses placeholders.
const persons = [
  [0, null], [1, "/"],
  [2, "เจ้าหน้าที่ 2"], [3, "เจ้าหน้าที่ 3"], [4, "เจ้าหน้าที่ 4"],
  [5, "เจ้าหน้าที่ 5"], [6, "เจ้าหน้าที่ 6"],
];
const dayCounts = [[1, 7], [2, 14], [3, 30], [4, 45], [5, 60], [6, 90], [7, 180], [8, 365], [9, 999]];

// ── Sets + per-month quantities from the Excel report ────────────────
const CONSUMABLE_RE = /สำลี|ก๊อส|ก็อส|ก้อส|ก๊อซ|gauze|dispose|สิ้นเปลือง/i;

const sets = []; // [SetTbId, Name1, Name2, Price]
const monthlyQty = []; // [SetTbId, CE year, month, qty, isConsumable, shelfDays]
let nextSet = 1;
let nextConsumable = 5001;
data.items.forEach((item) => {
  const unnamed = item.name.startsWith("(ไม่ระบุชื่อรายการ");
  const consumable = !unnamed && CONSUMABLE_RE.test(item.name);
  const id = consumable ? nextConsumable++ : nextSet++;
  const shelf = /180\s*วัน/.test(item.name) ? 180 : /14\s*วัน/.test(item.name) ? 14 : id % 2 ? 180 : 7;
  sets.push([id, sqlStr(String(id)), unnamed ? "NULL" : sqlStr(item.name), Number(item.pricePerUnit || 0).toFixed(2)]);
  for (const [key, qty] of Object.entries(item.monthlyQuantity ?? {})) {
    const m = key.match(/^(\d{4})-(\d{2})$/);
    if (!m || !qty) continue;
    monthlyQty.push([id, Number(m[1]) - 543, Number(m[2]), qty, consumable ? 1 : 0, shelf]);
  }
});

const totalQty = monthlyQty.reduce((s, r) => s + r[3], 0);
const maxQty = Math.max(...monthlyQty.map((r) => r[3]), 1);

const sql = `-- GENERATED by db/mock/generate-seed.mjs from ${path.basename(inputPath)} — do not edit.
-- ${sets.length} sets/consumables, ${totalQty} pieces dispensed (FY${data.fiscalYear ?? "?"}).
USE CSSD;
SET NOCOUNT ON;
GO

${insertChunks("dbo.DepartTb", ["DepartTbId", "DepartTbName"], departments.map(([id, n]) => [id, sqlStr(n)]))}
${insertChunks("dbo.PersonTb", ["PersonTbId", "PersonCall"], persons.map(([id, n]) => [id, sqlStr(n)]))}
${insertChunks("dbo.DayCountTb", ["DayCountTbId", "DayCountTbName"], dayCounts)}
${insertChunks("dbo.SetTb", ["SetTbId", "SetTbName1", "SetTbName2", "SetTbPrice"], sets)}
GO

CREATE TABLE #MockQty (SetTbId INT, Y INT, M INT, Qty INT, IsConsumable BIT, Shelf INT);
${insertChunks("#MockQty", ["SetTbId", "Y", "M", "Qty", "IsConsumable", "Shelf"], monthlyQty)}

-- One row per dispense: a piece for barcoded sets, a batch of up to 10
-- for consumables. Mostly daytime timestamps, plus deliberate month-boundary
-- ones (midnight on the 1st, 23:59:59.997 on the last day).
WITH Tally AS (
  SELECT TOP (${maxQty}) ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS N
  FROM sys.all_objects a CROSS JOIN sys.all_objects b
),
Expanded AS (
  SELECT q.SetTbId, q.IsConsumable, q.Shelf, t.N,
         CASE WHEN q.IsConsumable = 1 THEN (q.Qty + 9) / 10 ELSE q.Qty END AS Rows_,
         CASE WHEN q.IsConsumable = 1
              THEN CASE WHEN t.N * 10 <= q.Qty THEN 10 ELSE q.Qty - (t.N - 1) * 10 END
              ELSE 1 END AS Pieces,
         DATEFROMPARTS(q.Y, q.M, 1) AS MonthStart,
         DAY(EOMONTH(DATEFROMPARTS(q.Y, q.M, 1))) AS DaysInMonth
  FROM #MockQty q
  JOIN Tally t ON t.N <= CASE WHEN q.IsConsumable = 1 THEN (q.Qty + 9) / 10 ELSE q.Qty END
)
SELECT
  ROW_NUMBER() OVER (ORDER BY d.SupplyDate, e.SetTbId, e.N) AS SupplyNo,
  e.SetTbId, e.IsConsumable, e.Shelf, e.Pieces, d.SupplyDate,
  -- ~70% to the set's "home" department, the rest spread over 1–9
  CASE WHEN e.N % 10 < 7 THEN 2 + (e.SetTbId % 8) ELSE 1 + ((e.N + e.SetTbId) % 9) END AS DepartTbId,
  2 + ((e.N + e.SetTbId) % 5) AS PersonTbId
INTO #Disp
FROM Expanded e
CROSS APPLY (SELECT CASE
  WHEN e.N = 1 AND e.SetTbId % 5 = 0
    THEN CAST(e.MonthStart AS DATETIME)
  WHEN e.N = e.Rows_ AND e.SetTbId % 7 = 0
    THEN DATEADD(MILLISECOND, -3, CAST(DATEADD(MONTH, 1, e.MonthStart) AS DATETIME))
  ELSE DATEADD(MINUTE, 480 + ((e.N * 37 + e.SetTbId * 11) % 600),
         CAST(DATEADD(DAY, (e.N * 13 + e.SetTbId) % e.DaysInMonth, e.MonthStart) AS DATETIME))
END AS SupplyDate) d;

-- Placeholder pack 0 for consumables, like the real database.
INSERT INTO dbo.PackTb (PackTbNo, PackBarcode, SetTbPackDate, SetTbId, SetTbCountDate, SetTbExpireDate, SetTbPrice)
VALUES (0, 10000, NULL, NULL, NULL, NULL, NULL);

-- One physical pack per barcoded dispense, packed 0–4 days before it went
-- out; expiry = pack date + shelf life - 1 (the real data's convention).
INSERT INTO dbo.PackTb (PackTbNo, PackBarcode, SetTbPackDate, SetTbId, SetTbCountDate, SetTbExpireDate, SetTbPrice)
SELECT x.SupplyNo, 100000 + x.SupplyNo, x.PackDate, x.SetTbId, x.Shelf,
       DATEADD(DAY, x.Shelf - 1, x.PackDate), s.SetTbPrice
FROM (SELECT SupplyNo, SetTbId, Shelf,
             DATEADD(DAY, -(SupplyNo % 5), CAST(SupplyDate AS DATE)) AS PackDate
      FROM #Disp WHERE IsConsumable = 0) x
JOIN dbo.SetTb s ON s.SetTbId = x.SetTbId;

-- The real data has dispenses of sets that were later deleted from SetTb
-- (name gone, price only on the pack). Mimic that with the Excel's
-- blank-name items.
DELETE FROM dbo.SetTb WHERE SetTbName2 IS NULL;

-- Placeholder row SupplyNo 0, as seen in the real data.
INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount, SetTbId)
VALUES (0, NULL, 0, NULL, NULL, 0, 0, NULL);

INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount, SetTbId)
SELECT SupplyNo, CASE WHEN IsConsumable = 1 THEN 0 ELSE SupplyNo END,
       DepartTbId, PersonTbId, SupplyDate, 0, Pieces, SetTbId
FROM #Disp;

-- Just outside FY2568 on both sides — must NOT show up in the FY2568 report.
DECLARE @next INT = (SELECT MAX(SupplyNo) FROM dbo.SupplyTb);
DECLARE @set SMALLINT = (SELECT MIN(SetTbId) FROM dbo.SetTb);
INSERT INTO dbo.SupplyTb (SupplyNo, PackTbNo, DepartTbId, PersonTbId, SupplyDate, SupplyLabel, SuplyCount, SetTbId) VALUES
  (@next + 1, 0, 2, 2, '2024-09-30T23:59:59.997', 0, 1, @set),
  (@next + 2, 0, 2, 2, '2025-10-01T00:00:00.000', 0, 1, @set);

DROP TABLE #Disp;
DROP TABLE #MockQty;
GO

SELECT COUNT(*) AS SupplyRows, SUM(CAST(SuplyCount AS BIGINT)) AS Pieces FROM dbo.SupplyTb;
GO
`;

const outDir = path.join(here, "generated");
fs.mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, "02-seed.sql");
fs.writeFileSync(outPath, sql);
const consumables = sets.filter(([id]) => id >= 5001).length;
console.log(`wrote ${outPath}: ${sets.length} sets (${consumables} consumables), ${totalQty} pieces`);
